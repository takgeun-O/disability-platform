// Offline regression checks for public catalog coverage and easily confused models.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import Module from 'node:module';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
const root = fileURLToPath(new URL('../src/app/validation/hearing-aid-health-insurance', import.meta.url));
const mod = new Module(path.join(root, 'registry-content.cjs'));
mod.filename = path.join(root, 'registry-content.cjs');
mod._compile(ts.transpileModule(fs.readFileSync(path.join(root, 'registry-content.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, esModuleInterop: true } }).outputText, mod.filename);
const { registryProducts: products, matchProducts, isRegistryStale } = mod.exports;
assert.equal(products.length, 206);
assert.equal(new Set(products.map(p => p.id)).size, 206);
assert.deepEqual(['I','II','III','IV'].map(group => products.filter(p => p.group === group).length), [23,25,94,64]);
assert.ok(products.every(p => /^D\d{11}$/.test(p.id) && p.model && p.company && Number.isInteger(p.price)));
assert.equal(matchProducts('')[0], undefined);
assert.equal(matchProducts('nonexistent-model-123').length, 0);
assert.deepEqual(matchProducts(' d22018010015 ').map(p => p.model), ['Starkey Picasso 1000 CIC']);
assert.deepEqual(matchProducts('Ｓｔａｒｋｅｙ Picasso‐P 1000 CIC').map(p => p.id), ['D22018010016']);
assert.equal(matchProducts('Phonak Audeo L30-R')[0].price, 990000);
assert.equal(matchProducts('Phonak Sky L30-SP')[0].id, 'D22058085029');
assert.equal(matchProducts('Baha 6 Max')[0].price, 5200000);
assert.ok(matchProducts('Picasso').length > 6);
assert.ok(matchProducts('소노바').length > 1);
assert.ok(matchProducts('포낙').length > 0);
assert.ok(matchProducts('포낙').every(p => p.model.includes('Phonak')));
assert.equal(isRegistryStale('2026-09-23', Date.parse('2026-09-29T23:59:59+09:00')), false);
assert.equal(isRegistryStale('2026-09-23', Date.parse('2026-09-30T00:00:00+09:00')), true);
console.log('PASS: catalog coverage, model distinctions, aliases, no-match, prices, freshness boundary');
