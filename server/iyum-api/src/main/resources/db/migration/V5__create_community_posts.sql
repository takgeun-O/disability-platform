CREATE TABLE community_posts
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    author_id   BIGINT       NOT NULL,
    post_type   VARCHAR(20)  NOT NULL,
    topic       VARCHAR(32)  NOT NULL,

    title       VARCHAR(120) NOT NULL,
    content     TEXT         NOT NULL,

    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    deleted_at  TIMESTAMPTZ,

    CONSTRAINT fk_community_posts_author
        FOREIGN KEY (author_id)
            REFERENCES members (id)
            ON DELETE RESTRICT, /*게시글이 참조하는 회원을 DB에서 물리적으로 삭제하지 못하게 함*/

    CONSTRAINT ck_community_posts_type
        CHECK (
            post_type IN ('GENERAL', 'QUESTION', 'REVIEW')
        ),

    CONSTRAINT ck_community_posts_topic
        CHECK (
            topic IN (
                'DAILY',
                'HEARING_AID',
                'COCHLEAR_IMPLANT',
                'TREATMENT_REHABILITATION',
                'COMMUNICATION',
                'EMPLOYMENT',
                'WELFARE_LIFE'
            )
        ),

    CONSTRAINT ck_community_posts_title_length
        CHECK (char_length(title) BETWEEN 1 AND 120),

    CONSTRAINT ck_community_posts_content_length
        CHECK (char_length(content) BETWEEN 1 AND 10000)
);

-- 삭제되지 않은 게시글의 최신순 목록 조회
CREATE INDEX idx_community_posts_visible_latest
    ON community_posts (created_at DESC, id DESC)
    WHERE deleted_at IS NULL;

-- 작성자별 게시글 조회와 외래 키 관련 검사
CREATE INDEX idx_community_posts_author
    ON community_posts (author_id);