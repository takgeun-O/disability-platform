CREATE TABLE community_comments
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    post_id     BIGINT      NOT NULL,
    author_id   BIGINT      NOT NULL,
    content     TEXT        NOT NULL,

    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL,
    deleted_at  TIMESTAMPTZ,

--     게시글의 논리 삭제는 DELETE가 아니라 UPDATE이므로 외래키가 막지 않는다.
--     삭제된 게시글의 댓글을 노출하지 않는 처리는 서비스 계층에서 구현
--     굳이 ON DELETE RESTRICT를 거는 이유는 평소 논리 삭제를 하더라도
--     실수나 다른 경로로 실제 DELETE가 실행됐을 때 댓글과 게시글의 연결이
--     깨지는 것을 막기 위해서임. (게시글만 사라지고 댓글이 남는 상황 방지)
--     정말로 추후 오래된 데이터를 물리적으로(영구적으로) 삭제하려면
--     댓글부터 정리하고 게시글을 삭제하는 등 별도 절차 설계 필요
--     참고로 PostgreSQL에서 ON DELETE RESTRICT를 생략한다고 해도
--     기본값인 NO ACTION도 일반적인 경우 삭제를 막는다.
--     여기서는 댓글이 남아있으면 게시글의 물리 삭제를 제한한다라는 의도를 명시적으료 표현한 것
    CONSTRAINT fk_community_comments_post
        FOREIGN KEY (post_id)
            REFERENCES community_posts (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_community_comments_author
        FOREIGN KEY (author_id)
            REFERENCES members (id)
            ON DELETE RESTRICT,

    CONSTRAINT ck_community_comments_content_length
        CHECK (char_length(content) BETWEEN 1 AND 2000)
);

-- 게시글별 댓글 조회와 오래된 순 정렬
CREATE INDEX idx_community_comments_post_created
    ON community_comments (post_id, created_at, id);

-- 작성자 외래 키 관련 검사와 작성자별 조회
-- 첫 번째 인덱스 idx_community_comments_post_created 는
-- author_id가 없으므로 작성자 기준 조회를 직접 도와주지 못한다. 그래서 별도로 하나 더 만들음.
-- 이처럼 복합 인덱스를 볼 때는 "어떤 컬럼부터 정리되어 있는가?"가 중요하다.
-- 다만 인덱스가 많아지면 아래와 같은 트레이드오프를 신경써야 한다.
-- 1. 인덱스를 저장할 공간이 더 필요
-- 2. 댓글 등록 시 테이블 뿐만 아니라 인덱스도 갱신해야 함
-- 3. 인덱스 대상 값 변경이나 물리 삭제에도 관리 비용 발생
-- 따라서 자주 사용하는 조회 조건과 정렬 방식에 맞춰 "꼭" 필요한 인덱스를 만드는 것이 중요
CREATE INDEX idx_community_comments_author
    ON community_comments (author_id);