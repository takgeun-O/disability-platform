-- 로그인 당시 인증 버전과 현재 회원의 인증 버전을 비교하기 위한 값.
-- 기존 회원과 신규 회원 모두 0부터 시작한다.
ALTER TABLE members
    ADD COLUMN credential_version BIGINT NOT NULL DEFAULT 0;

ALTER TABLE members
    ADD CONSTRAINT ck_members_credential_version
        CHECK (credential_version >= 0);


-- 비밀번호 재설정 전용 토큰.
-- 이메일 인증 토큰과 분리하여 서로 다른 용도로 사용되지 않게 한다.
CREATE TABLE password_reset_tokens
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    member_id   BIGINT      NOT NULL,
    token_hash  VARCHAR(64) NOT NULL,

    created_at  TIMESTAMPTZ NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    used_at     TIMESTAMPTZ,
    revoked_at  TIMESTAMPTZ,

    version     BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT fk_password_reset_tokens_member
        FOREIGN KEY (member_id)
            REFERENCES members (id)
            ON DELETE RESTRICT,

    CONSTRAINT uk_password_reset_tokens_hash
        UNIQUE (token_hash),

    CONSTRAINT ck_password_reset_tokens_hash
        CHECK (token_hash ~ '^[0-9a-f]{64}$'),

    CONSTRAINT ck_password_reset_tokens_expiration
        CHECK (expires_at > created_at),

    CONSTRAINT ck_password_reset_tokens_used_at
        CHECK (
            used_at IS NULL
            OR (used_at >= created_at AND used_at < expires_at)
        ),

    CONSTRAINT ck_password_reset_tokens_revoked_at
        CHECK (
            revoked_at IS NULL
            OR revoked_at >= created_at
        ),

    CONSTRAINT ck_password_reset_tokens_terminal_state
        CHECK (used_at IS NULL OR revoked_at IS NULL),

    CONSTRAINT ck_password_reset_tokens_version
        CHECK (version >= 0)
);

-- 회원별 토큰 조회와 최근 발급 시각·발급 횟수 조회에 사용한다.
CREATE INDEX idx_password_reset_tokens_member_created
    ON password_reset_tokens (member_id, created_at DESC);