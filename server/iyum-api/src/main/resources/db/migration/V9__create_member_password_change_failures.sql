CREATE TABLE member_password_change_failures
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id     BIGINT      NOT NULL,
    failed_at     TIMESTAMPTZ NOT NULL,
    blocked_until TIMESTAMPTZ,

    CONSTRAINT fk_member_password_change_failures_member
        FOREIGN KEY (member_id)
            REFERENCES members (id)
            ON DELETE CASCADE, -- 회원 행을 실제로 삭제할 때 해당 실패 기록도 삭제한다.

    CONSTRAINT ck_member_password_change_failures_blocked_until
        CHECK (
            blocked_until IS NULL
                OR blocked_until > failed_at
            )
);

CREATE INDEX idx_member_password_change_failures_member_failed
    ON member_password_change_failures (member_id, failed_at DESC);