CREATE TABLE admin_member_moderation_logs
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_member_id  BIGINT       NOT NULL,
    target_member_id BIGINT       NOT NULL,
    action           VARCHAR(30)  NOT NULL,
    before_status    VARCHAR(20)  NOT NULL,
    after_status     VARCHAR(20)  NOT NULL,
    reason           VARCHAR(500) NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL,

    CONSTRAINT fk_member_moderation_logs_actor
        FOREIGN KEY (actor_member_id)
            REFERENCES members (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_member_moderation_logs_target
        FOREIGN KEY (target_member_id)
            REFERENCES members (id)
            ON DELETE RESTRICT,

    CONSTRAINT ck_member_moderation_logs_distinct_members
        CHECK (actor_member_id <> target_member_id),

--     올바른 상태 변화인지 검사
    CONSTRAINT ck_member_moderation_logs_transition
--         다음 두 조합만 허용한다.
--         SUSPEND 정지 - 이전 상태: ACTIVE - 이후 상태: SUSPEND
        CHECK (
            (
                action = 'SUSPEND'
                AND before_status = 'ACTIVE'
                AND after_status = 'SUSPENDED'
            )
            OR
            (
                action = 'LIFT_SUSPENSION'
                AND before_status = 'SUSPENDED'
                AND after_status = 'ACTIVE'
                )
            ),

    CONSTRAINT ck_member_moderation_logs_reason
        CHECK (char_length(btrim(reason)) BETWEEN 1 AND 500)
);

