CREATE TABLE community_comment_likes
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    comment_id BIGINT      NOT NULL,
    member_id  BIGINT      NOT NULL,

    created_at TIMESTAMPTZ NOT NULL,

    -- 좋아요가 연결된 댓글
    CONSTRAINT fk_community_comment_likes_comment
        FOREIGN KEY (comment_id)
            REFERENCES community_comments (id)
            ON DELETE RESTRICT,

    -- 좋아요를 누른 회원
    CONSTRAINT fk_community_comment_likes_member
        FOREIGN KEY (member_id)
            REFERENCES members (id)
            ON DELETE RESTRICT,

    -- 한 회원은 같은 댓글에 좋아요를 하나만 등록할 수 있음
    CONSTRAINT uk_community_comment_likes_comment_member
        UNIQUE (comment_id, member_id)
);

-- 회원 기준 조회와 회원 외래 키 관련 검사에 사용
CREATE INDEX idx_community_comment_likes_member
    ON community_comment_likes (member_id);