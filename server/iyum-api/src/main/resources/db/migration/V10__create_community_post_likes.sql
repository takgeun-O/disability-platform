CREATE TABLE community_post_likes
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    post_id    BIGINT      NOT NULL,
    member_id  BIGINT      NOT NULL,

    created_at TIMESTAMPTZ NOT NULL,

    -- 좋아요가 연결된 게시글
    -- 연결된 좋아요가 남아 있으면 게시글 물리 삭제 제한
    -- 단, deleted_at을 변경하는 논리 삭제는 막지 않음.
    CONSTRAINT fk_community_post_likes_post
        FOREIGN KEY (post_id)
            REFERENCES community_posts (id)
            ON DELETE RESTRICT,

    -- 좋아요를 누른 회원
    CONSTRAINT fk_community_post_likes_member
        FOREIGN KEY (member_id)
            REFERENCES members (id)
            ON DELETE RESTRICT,

    -- 한 회원이 같은 게시글에 중복으로 좋아요를 등록하지 못하도록 제한
    CONSTRAINT uk_community_post_likes_post_member
        UNIQUE (post_id, member_id)
);

-- 회원별 좋아요 조회와 회원 외래 키 관련 검사에 사용
-- (post_id, member_id) 인덱스는 게시글 기준 조회에도 활용할 수 있으므로
-- 여기서는 회원 기준 조회를 위한 member_id 인덱스만 추가하였음.
CREATE INDEX idx_community_post_likes_member
    ON community_post_likes (member_id);