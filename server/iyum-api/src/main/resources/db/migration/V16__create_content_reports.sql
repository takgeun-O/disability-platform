CREATE TABLE content_reports
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reporter_member_id BIGINT      NOT NULL,

    -- 신고의 직접 대상은 게시글 또는 댓글 중 하나다.
    post_id            BIGINT,
    comment_id         BIGINT,

    reason_type        VARCHAR(40) NOT NULL,
    reason_detail      VARCHAR(500),

    -- 접수 당시 내용. 현재 콘텐츠와 별도로 보존한다.
    title_snapshot     TEXT,
    content_snapshot   TEXT        NOT NULL,

    status             VARCHAR(20) NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_content_reports_reporter
        FOREIGN KEY (reporter_member_id)
            REFERENCES members (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_content_reports_post
        FOREIGN KEY (post_id)
            REFERENCES community_posts (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_content_reports_comment
        FOREIGN KEY (comment_id)
            REFERENCES community_comments (id)
            ON DELETE RESTRICT,

    -- 두 대상 중 정확히 하나만 지정한다.
    CONSTRAINT ck_content_reports_target
        CHECK (
            (post_id IS NOT NULL AND comment_id IS NULL)
                OR
            (post_id IS NULL AND comment_id IS NOT NULL)
        ),

    CONSTRAINT ck_content_reports_reason_type
        CHECK (
            reason_type IN (
                'SPAM_ADVERTISING',
                'ABUSE_HATE',
                'PERSONAL_INFORMATION',
                'DUPLICATE_FLOODING',
                'OFF_TOPIC',
                'OTHER'
            )
        ),

    -- 상세 설명이 없으면 null이다.
    -- 값이 있으면 빈 문자열·일반 공백만 있는 값은 허용하지 않는다.
    CONSTRAINT ck_content_reports_reason_detail
        CHECK (
            reason_detail IS NULL
                OR (
                    char_length(reason_detail) BETWEEN 1 AND 500
                    AND char_length(btrim(reason_detail)) > 0
                )
        ),

    CONSTRAINT ck_content_reports_other_detail
        CHECK (
            reason_type <> 'OTHER'
                OR reason_detail IS NOT NULL
        ),

    -- 게시글 신고는 제목이 필수이고, 댓글 신고는 제목이 null이다.
    CONSTRAINT ck_content_reports_title_snapshot
        CHECK (
            (
                post_id IS NOT NULL
                AND title_snapshot IS NOT NULL
                AND char_length(btrim(title_snapshot)) > 0
            )
                OR
            (
                comment_id IS NOT NULL
                AND title_snapshot IS NULL
            )
        ),

    CONSTRAINT ck_content_reports_content_snapshot
        CHECK (
            char_length(btrim(content_snapshot)) > 0
        ),

    CONSTRAINT ck_content_reports_status
        CHECK (
            status IN (
                'RECEIVED',
                'RESOLVED',
                'DISMISSED'
            )
        )
);

-- 같은 회원은 같은 게시글에 한 번만 신고할 수 있다.
-- 유니크 인덱스 활용함으로써 같은 쌍이 두 번 저장되면 거절한다.
CREATE UNIQUE INDEX uq_content_reports_post_reporter
    ON content_reports (post_id, reporter_member_id)
    WHERE post_id IS NOT NULL;  -- 게시글 신고만 이 인덱스에 담는다.

-- 같은 회원은 같은 댓글에 한 번만 신고할 수 있다.
CREATE UNIQUE INDEX uq_content_reports_comment_reporter
    ON content_reports (comment_id, reporter_member_id)
    WHERE comment_id IS NOT NULL;

-- 신고자별 조회 및 외래 키 참조 검색.
CREATE INDEX idx_content_reports_reporter_created
    ON content_reports (
        reporter_member_id,
        created_at DESC,
        id DESC
    );

-- 관리자 전체 신고 목록.
CREATE INDEX idx_content_reports_created
    ON content_reports (
        created_at DESC,
        id DESC
    );

-- 관리자 처리 상태별 신고 목록.
CREATE INDEX idx_content_reports_status_created
    ON content_reports (
        status,
        created_at DESC,
        id DESC
    );