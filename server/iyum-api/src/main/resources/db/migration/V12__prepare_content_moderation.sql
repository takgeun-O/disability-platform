-- 관리자 숨김 상태는 작성자 삭제 상태와 별도로 관리한다.
ALTER TABLE community_posts
    ADD COLUMN hidden_at TIMESTAMPTZ;

ALTER TABLE community_comments
    ADD COLUMN hidden_at TIMESTAMPTZ;

-- 관리자에 의한 게시글·댓글 숨김 및 복원 이력
CREATE TABLE admin_content_moderation_logs
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    actor_member_id BIGINT       NOT NULL,

    -- 게시글 처리이면 post_id만, 댓글 처리이면 comment_id만 기록한다.
    post_id         BIGINT,
    comment_id      BIGINT,

    action          VARCHAR(20)  NOT NULL,
    reason          VARCHAR(500) NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL,

    CONSTRAINT fk_admin_moderation_logs_actor
        FOREIGN KEY (actor_member_id)
            REFERENCES members (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_admin_moderation_logs_post
        FOREIGN KEY (post_id)
            REFERENCES community_posts (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_admin_moderation_logs_comment
        FOREIGN KEY (comment_id)
            REFERENCES community_comments (id)
            ON DELETE RESTRICT,

    -- 처리 대상은 게시글 또는 댓글 중 정확히 하나여야 한다.
    CONSTRAINT ck_admin_moderation_logs_target
        CHECK (
            (post_id IS NOT NULL AND comment_id IS NULL)
                OR
            (post_id IS NULL AND comment_id IS NOT NULL)
            ),

    CONSTRAINT ck_admin_moderation_logs_action
        CHECK (action IN ('HIDE', 'RESTORE')),

    CONSTRAINT ck_admin_moderation_logs_reason
        CHECK (char_length(btrim(reason)) BETWEEN 1 AND 500)
);

-- 게시글별 처리 이력
CREATE INDEX idx_admin_moderation_logs_post_created
    ON admin_content_moderation_logs (
                                      post_id, created_at DESC, id DESC
        )
    WHERE post_id IS NOT NULL;

-- 댓글별 처리 이력
CREATE INDEX idx_admin_moderation_logs_comment_created
    ON admin_content_moderation_logs (
                                      comment_id, created_at DESC, id DESC
        )
    WHERE comment_id IS NOT NULL;

-- 처리 관리자별 이력
CREATE INDEX idx_admin_moderation_logs_actor_created
    ON admin_content_moderation_logs (
                                      actor_member_id, created_at DESC, id DESC
        );